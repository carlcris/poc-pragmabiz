"use client";

import { useTranslations } from "next-intl";

import type { RequisitionRow } from "@/lib/framing/documents";

type RequisitionPaperProps = {
  rows: RequisitionRow[];
  totalSales: string;
  customerName?: string;
  customerAddress?: string;
  transactionNumber?: string;
  preparedBy?: string;
  showFooter?: boolean;
};

/** Ruled rows drawn on an unconfigured form, so it keeps a page's proportions. */
const BLANK_ROW_COUNT = 3;

/**
 * The shared on-screen Job Requisition Form used while configuring a frame and
 * when viewing a persisted frame job order.
 */
export function RequisitionPaper({
  rows,
  totalSales,
  customerName,
  customerAddress,
  transactionNumber,
  preparedBy,
  showFooter = true,
}: RequisitionPaperProps) {
  const t = useTranslations("framingDocuments");

  return (
    <div className="rounded-md bg-white p-5 text-[12.5px] leading-relaxed text-neutral-900 shadow-lg">
      <h3 className="mb-0.5 text-center text-[15px] font-extrabold uppercase">
        {t("requisitionTitle")}
      </h3>
      <p className="mb-4 text-center text-[10px] uppercase tracking-[0.06em] text-neutral-500">
        {t("shopLine")}
      </p>

      <div className="mb-3.5 grid grid-cols-1 gap-x-6 gap-y-1.5 sm:grid-cols-[1.2fr_1fr]">
        <div className="grid grid-cols-[auto_1fr] items-baseline gap-x-2 gap-y-1.5 self-start">
          <PaperField label={t("customer")} value={customerName} />
          <PaperField label={t("address")} value={customerAddress} placeholder={t("noAddress")} />
        </div>
        <div className="grid grid-cols-[auto_1fr] items-baseline gap-x-2 gap-y-1.5 self-start">
          <PaperField
            label={t("transactionNo")}
            value={transactionNumber}
            placeholder={t("autoGenerated")}
            mono
          />
        </div>
      </div>

      <table className="mb-3 w-full border-collapse border-[1.5px] border-neutral-800">
        <thead>
          <tr>
            <th className="w-[58px] border border-neutral-800 p-1.5 text-[11px] font-extrabold">
              {t("actualQty")}
            </th>
            <th className="w-[40px] border border-neutral-800 p-1.5 text-[11px] font-extrabold">
              {t("qty")}
            </th>
            <th className="w-[44px] border border-neutral-800 p-1.5 text-[11px] font-extrabold">
              {t("unit")}
            </th>
            <th className="border border-neutral-800 p-1.5 text-[11px] font-extrabold" colSpan={2}>
              {t("articleDescription")}
            </th>
          </tr>
        </thead>
        <tbody>
          {rows.length === 0
            ? Array.from({ length: BLANK_ROW_COUNT }, (_, index) => (
                <tr key={`blank-${index}`}>
                  <td className="h-[38px] border border-neutral-800 p-1.5" />
                  <td className="border border-neutral-800 p-1.5" />
                  <td className="border border-neutral-800 p-1.5" />
                  <td className="border border-neutral-800 p-1.5" colSpan={2} />
                </tr>
              ))
            : null}
          {rows.map((row, index) => (
            <tr key={index}>
              <td className="border border-neutral-800 p-1.5" />
              <td className="border border-neutral-800 p-1.5 text-center font-mono font-bold">
                {row.quantity}
              </td>
              <td className="border border-neutral-800 p-1.5 text-center font-mono font-bold">
                {row.unit}
              </td>
              <td className="w-px whitespace-nowrap border border-neutral-800 p-1.5 align-top">
                <DimensionPair
                  lengthIn={row.artwork.lengthIn}
                  widthIn={row.artwork.widthIn}
                  label={t("artworkSize")}
                />
                {row.matOuter ? (
                  <DimensionPair
                    lengthIn={row.matOuter.lengthIn}
                    widthIn={row.matOuter.widthIn}
                    label={t("matSize")}
                  />
                ) : null}
                {row.matBorders.length > 0 ? (
                  <div className="mt-1 border-t border-neutral-200 pt-1">
                    {row.matBorders.map((border, borderIndex) => (
                      <div
                        key={`${border.label}-${borderIndex}`}
                        className="text-[10px] leading-snug text-neutral-700"
                      >
                        {border.label ? (
                          <span className="text-neutral-500">{border.label} </span>
                        ) : null}
                        {border.text}
                      </div>
                    ))}
                  </div>
                ) : null}
              </td>
              <td className="border border-neutral-800 p-1.5 align-top">
                {row.articles.map((block) => (
                  <div key={block.heading} className="mb-1.5 last:mb-0">
                    <div className="text-[9px] font-extrabold uppercase tracking-[0.09em] text-neutral-500">
                      {block.heading}
                    </div>
                    {block.lines.map((line, lineIndex) => (
                      <div
                        key={`${block.heading}-${lineIndex}`}
                        className={`leading-snug ${block.emphasis ? "font-bold" : ""} ${
                          line.bullet
                            ? "relative pl-2.5 before:absolute before:left-0.5 before:text-neutral-500 before:content-['·']"
                            : ""
                        }`}
                      >
                        {line.text}
                      </div>
                    ))}
                  </div>
                ))}
                {row.instructions ? (
                  <div className="mt-1.5 border-t border-neutral-300 pt-1.5">
                    <div className="text-[9px] font-extrabold uppercase tracking-[0.09em] text-neutral-500">
                      {t("instructions")}
                    </div>
                    <div className="whitespace-pre-wrap leading-snug">{row.instructions}</div>
                  </div>
                ) : null}
              </td>
            </tr>
          ))}
        </tbody>
      </table>

      {showFooter ? (
        <>
          <div className="flex justify-end gap-6 border-t border-neutral-200 pt-1.5 text-[11.5px]">
            <div className="text-right">
              <span className="mb-0.5 block text-[9.5px] font-bold uppercase tracking-[0.08em] text-neutral-500">
                {t("totalCuts")}
              </span>
              <b className="font-mono text-[13px] tabular-nums">
                {rows.reduce((total, entry) => total + entry.quantity, 0)}
              </b>
            </div>
            <div className="text-right">
              <span className="mb-0.5 block text-[9.5px] font-bold uppercase tracking-[0.08em] text-neutral-500">
                {t("totalSales")}
              </span>
              <b className="font-mono text-[13px] tabular-nums">{totalSales}</b>
            </div>
          </div>

          <div className="mt-6 grid grid-cols-2 gap-6">
            <SignatureLine label={t("preparedBy")} name={preparedBy} />
            <SignatureLine label={t("receivedBy")} />
          </div>
        </>
      ) : null}
    </div>
  );
}

function PaperField({
  label,
  value,
  placeholder,
  mono,
}: {
  label: string;
  value?: string;
  placeholder?: string;
  mono?: boolean;
}) {
  const empty = !value;

  return (
    <>
      <span className="whitespace-nowrap text-[11px] font-bold text-neutral-700">{label}</span>
      <span
        className={`min-h-4 border-b border-neutral-700 px-0.5 pb-px text-[11.5px] font-semibold ${
          mono ? "font-mono text-[11px]" : ""
        } ${empty ? "font-normal italic text-neutral-400" : ""}`}
      >
        {value || placeholder || ""}
      </span>
    </>
  );
}

function DimensionPair({
  lengthIn,
  widthIn,
  label,
}: {
  lengthIn: string;
  widthIn: string;
  label?: string;
}) {
  return (
    <div className="mb-0.5 last:mb-0">
      {label ? (
        <div className="text-[8px] font-bold uppercase tracking-[0.08em] text-neutral-500">
          {label}
        </div>
      ) : null}
      <div className="flex items-center gap-1.5 py-px font-mono text-[11px] font-bold">
        <span className="min-w-9 whitespace-nowrap border-b border-neutral-700 px-0.5 text-center">
          {lengthIn}
        </span>
        <span className="shrink-0">X</span>
        <span className="min-w-9 whitespace-nowrap border-b border-neutral-700 px-0.5 text-center">
          {widthIn}
        </span>
      </div>
    </div>
  );
}

function SignatureLine({ label, name }: { label: string; name?: string }) {
  return (
    <div>
      <div className="min-h-[14px] text-center text-[11px] font-semibold text-neutral-800">
        {name ?? ""}
      </div>
      <div className="border-t border-neutral-700 pt-1 text-center text-[10px] text-neutral-600">
        {label}
      </div>
    </div>
  );
}
