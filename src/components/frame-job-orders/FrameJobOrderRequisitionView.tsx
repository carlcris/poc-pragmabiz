"use client";

import { useState } from "react";
import { useTranslations } from "next-intl";
import { toast } from "sonner";

import { RequisitionPaper } from "@/components/framing/RequisitionPaper";
import { Button } from "@/components/ui/button";
import { useCurrency } from "@/hooks/useCurrency";
import type { FrameJobOrderRequisitionDocument } from "@/lib/frame-job-orders/requisition";

type FrameJobOrderRequisitionViewProps = {
  requisition: FrameJobOrderRequisitionDocument;
  showDocumentActions?: boolean;
  showPaperFooter?: boolean;
};

export function FrameJobOrderRequisitionView({
  requisition,
  showDocumentActions = true,
  showPaperFooter = true,
}: FrameJobOrderRequisitionViewProps) {
  const t = useTranslations("framingDocuments");
  const { formatCurrency } = useCurrency();
  const [busy, setBusy] = useState<"print" | "download" | null>(null);
  const totalSales = formatCurrency(requisition.totalSales);

  const runAction = async (action: "print" | "download") => {
    if (busy) return;

    setBusy(action);
    try {
      const [{ pdf }, { RequisitionPDF }, { openPdf, savePdf }] = await Promise.all([
        import("@react-pdf/renderer"),
        import("@/components/framing/RequisitionPDF"),
        import("@/lib/framing/printDocument"),
      ]);
      const pdfDocument = (
        <RequisitionPDF
          rows={requisition.rows}
          totalSales={totalSales}
          customerName={requisition.customerName}
          customerAddress={requisition.customerAddress}
          transactionNumber={requisition.transactionNumber}
          preparedBy={requisition.preparedBy}
          labels={{
            title: t("requisitionTitle"),
            shopLine: t("shopLine"),
            customer: t("customer"),
            address: t("address"),
            noAddress: t("noAddress"),
            transactionNo: t("transactionNo"),
            autoGenerated: t("autoGenerated"),
            actualQty: t("actualQty"),
            qty: t("qty"),
            unit: t("unit"),
            articleDescription: t("articleDescription"),
            artworkSize: t("artworkSize"),
            matSize: t("matSize"),
            totalCuts: t("totalCuts"),
            totalSales: t("totalSales"),
            preparedBy: t("preparedBy"),
            receivedBy: t("receivedBy"),
          }}
        />
      );
      const blob = await pdf(pdfDocument).toBlob();

      if (action === "print") {
        await openPdf(blob);
      } else {
        savePdf(blob, `job-requisition-${requisition.transactionNumber}.pdf`);
      }
    } catch (error) {
      console.error("Failed to prepare job order requisition:", error);
      toast.error(
        error instanceof Error && error.message === "POPUP_BLOCKED"
          ? t("popupBlocked")
          : t("documentActionFailed")
      );
    } finally {
      setBusy(null);
    }
  };

  return (
    <section className="space-y-4">
      <div className="overflow-x-auto rounded-lg border bg-muted/30 p-3 sm:p-6">
        <div className="mx-auto min-w-[48rem] max-w-5xl">
          <RequisitionPaper
            rows={requisition.rows}
            totalSales={totalSales}
            customerName={requisition.customerName}
            customerAddress={requisition.customerAddress}
            transactionNumber={requisition.transactionNumber}
            preparedBy={requisition.preparedBy}
            showFooter={showPaperFooter}
          />
        </div>
      </div>
      {showDocumentActions ? (
        <div className="flex flex-wrap gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={busy !== null}
            onClick={() => void runAction("print")}
          >
            {busy === "print" ? t("printing") : t("print")}
          </Button>
          <Button
            type="button"
            variant="outline"
            disabled={busy !== null}
            onClick={() => void runAction("download")}
          >
            {busy === "download" ? t("preparing") : t("downloadPdf")}
          </Button>
        </div>
      ) : null}
    </section>
  );
}
